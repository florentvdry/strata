// Turns what `tauri build` made into the files a release ships, with the names the website and the update manifest use.
//
//   node scripts/package-release.js            (after `npm run build` / `npm run build:linux`, from the repo root)
//
// Windows: Strata-Setup-<v>.exe, Strata-<v>-Portable.exe (the program itself: the scanner is inside it)
// Linux:   Strata-<v>-amd64.deb, -x86_64.rpm, -x86_64.AppImage, -x64.pacman, -x64.tar.gz
// Each file the updater installs gets a .sig next to it (made here when `tauri build` didn't).
// Signing needs TAURI_SIGNING_PRIVATE_KEY (and _PASSWORD if it has one); without it the files are unsigned.
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const root = path.join(__dirname, '..');
const version = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).version;
const target = path.join(root, 'src', 'app', 'target', 'release');
const bundle = path.join(target, 'bundle');
const out = path.join(root, 'dist');
const IS_WIN = process.platform === 'win32';
const tauriBin = path.join(root, 'node_modules', '.bin', IS_WIN ? 'tauri.cmd' : 'tauri');

fs.mkdirSync(out, { recursive: true });

// `tauri build` stamps the kind of bundle it made (deb, rpm, nsis…) into target/release/strata, and the app uses that
// stamp to decide how to update itself. The portable .exe, the .tar.gz and the pacman package are not any of those,
// so they get a copy with the stamp set back to "unknown": they must never try to install an AppImage over themselves.
function neutral(from, to) {
  let buf = fs.readFileSync(from);
  for (const kind of ['DEB', 'RPM', 'APP', 'MSI', 'NSS']) {
    const stamp = Buffer.from(`__TAURI_BUNDLE_TYPE_VAR_${kind}`);
    const unknown = Buffer.from('__TAURI_BUNDLE_TYPE_VAR_UNK');
    let at;
    while ((at = buf.indexOf(stamp)) >= 0) unknown.copy(buf, at);
  }
  fs.writeFileSync(to, buf);
  fs.chmodSync(to, 0o755);
}

function find(dir, re) {
  if (!fs.existsSync(dir)) return null;
  const f = fs.readdirSync(dir).find((n) => re.test(n));
  return f ? path.join(dir, f) : null;
}

function need(p, what) {
  if (!p) { console.error(`Missing ${what}. Run the build first.`); process.exit(1); }
  return p;
}

function put(from, name) {
  const to = path.join(out, name);
  fs.copyFileSync(from, to);
  const sig = `${from}.sig`;
  if (fs.existsSync(sig)) fs.copyFileSync(sig, `${to}.sig`);
  console.log(`  ${name}${fs.existsSync(`${to}.sig`) ? '  (signed)' : ''}`);
  return to;
}

function sign(file) {
  if (fs.existsSync(`${file}.sig`) || !process.env.TAURI_SIGNING_PRIVATE_KEY) return;
  execFileSync(tauriBin, ['signer', 'sign', file], { stdio: 'inherit', shell: IS_WIN });
}

function pacman(binary) {
  const stage = fs.mkdtempSync(path.join(require('os').tmpdir(), 'strata-pacman-'));
  const put0 = (rel, from, mode) => {
    const to = path.join(stage, rel);
    fs.mkdirSync(path.dirname(to), { recursive: true });
    fs.copyFileSync(from, to);
    fs.chmodSync(to, mode);
  };
  put0('usr/bin/strata', binary, 0o755);
  put0('usr/share/icons/hicolor/128x128/apps/strata.png', path.join(root, 'src', 'app', 'icons', '128x128.png'), 0o644);
  put0('usr/share/licenses/strata/LICENSE', path.join(root, 'LICENSE'), 0o644);
  fs.mkdirSync(path.join(stage, 'usr/share/applications'), { recursive: true });
  fs.writeFileSync(path.join(stage, 'usr/share/applications/strata.desktop'), desktopFile());
  const size = fs.statSync(binary).size;
  // pacman versions can't contain "-": 0.2.0-beta.1 becomes 0.2.0_beta.1
  fs.writeFileSync(path.join(stage, '.PKGINFO'), [
    '# Generated by scripts/package-release.js',
    'pkgname = strata', 'pkgbase = strata', `pkgver = ${version.replace(/-/g, '_')}-1`,
    'pkgdesc = See what fills your disk, then clean it up', 'url = https://github.com/florentvdry/strata',
    `builddate = ${Math.floor(Date.now() / 1000)}`, 'packager = Florent Vandroy', `size = ${size}`, 'arch = x86_64', 'license = MIT',
    'depend = webkit2gtk-4.1', 'depend = gtk3', '',
  ].join('\n'));
  const file = path.join(out, `Strata-${version}-x64.pacman`);
  execFileSync('tar', ['--zstd', '--owner=0', '--group=0', '--numeric-owner', '-cf', file, '-C', stage, '.PKGINFO', 'usr'], { stdio: 'inherit' });
  fs.rmSync(stage, { recursive: true, force: true });
  console.log(`  ${path.basename(file)}`);
}

function desktopFile() {
  return ['[Desktop Entry]', 'Type=Application', 'Name=Strata', 'Comment=See what fills your disk, then clean it up', 'Exec=strata', 'Icon=strata',
    'Terminal=false', 'Categories=Utility;System;', 'StartupWMClass=strata', ''].join('\n');
}

function tarball(binary) {
  const stage = fs.mkdtempSync(path.join(require('os').tmpdir(), 'strata-tar-'));
  fs.copyFileSync(binary, path.join(stage, 'strata'));
  fs.chmodSync(path.join(stage, 'strata'), 0o755);
  fs.copyFileSync(path.join(root, 'LICENSE'), path.join(stage, 'LICENSE'));
  fs.copyFileSync(path.join(root, 'src', 'app', 'icons', '128x128.png'), path.join(stage, 'strata.png'));
  fs.writeFileSync(path.join(stage, 'strata.desktop'), desktopFile());
  const file = path.join(out, `Strata-${version}-x64.tar.gz`);
  execFileSync('tar', ['--owner=0', '--group=0', '--numeric-owner', '-czf', file, '-C', stage, 'strata', 'LICENSE', 'strata.png', 'strata.desktop'], { stdio: 'inherit' });
  fs.rmSync(stage, { recursive: true, force: true });
  console.log(`  ${path.basename(file)}`);
}

console.log(`Packaging Strata ${version} into dist/`);
if (IS_WIN) {
  const setup = need(find(path.join(bundle, 'nsis'), /-setup\.exe$/), 'the NSIS installer');
  sign(put(setup, `Strata-Setup-${version}.exe`));
  const exe = need(fs.existsSync(path.join(target, 'strata.exe')) && path.join(target, 'strata.exe'), 'target/release/strata.exe');
  // The portable build is the program itself; the updater verifies its signature before swapping the file.
  const portable = path.join(out, `Strata-${version}-Portable.exe`);
  neutral(exe, portable);
  sign(portable);
  console.log(`  ${path.basename(portable)}${fs.existsSync(`${portable}.sig`) ? '  (signed)' : ''}`);
} else {
  sign(put(need(find(path.join(bundle, 'deb'), /\.deb$/), 'the .deb'), `Strata-${version}-amd64.deb`));
  // RPM versions can't contain "-", so a pre-release (0.3.0-beta.1) has no .rpm: Fedora users take the AppImage.
  const rpm = find(path.join(bundle, 'rpm'), /\.rpm$/);
  if (rpm) sign(put(rpm, `Strata-${version}-x86_64.rpm`));
  else if (!version.includes('-')) need(null, 'the .rpm');
  else console.warn('  (no .rpm for a pre-release)');
  const appimage = find(path.join(bundle, 'appimage'), /\.AppImage$/);
  if (appimage) sign(put(appimage, `Strata-${version}-x86_64.AppImage`));
  else console.warn('  (no AppImage was built)');
  const raw = need(fs.existsSync(path.join(target, 'strata')) && path.join(target, 'strata'), 'target/release/strata');
  const binary = path.join(out, '.strata-unstamped');
  neutral(raw, binary);
  tarball(binary);
  pacman(binary);
  fs.rmSync(binary);
}
